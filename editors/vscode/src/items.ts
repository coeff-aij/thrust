// The functions of a Rust file and their paths in `THRUST_VERIFY_ONLY`'s syntax, read from the
// text without a compiler: enough to put a code lens above each function and to name it for a
// run of that function only. Nothing here depends on VS Code.

import * as path from "path";

/// A function with a body, at item level of the file, of a module or of an `impl` or `trait`
/// block in it.
export interface FnItem {
  name: string;
  /// The path within the file: modules, the `impl`'s self type or the trait, the function.
  path: string[];
  /// The 1-based line of the item's first attribute or keyword, and of its closing brace.
  line: number;
  endLine: number;
}

interface Token {
  text: string;
  kind: "ident" | "punct" | "literal" | "lifetime";
  line: number;
}

/// The functions of `text`, in their order in it.
///
/// Functions inside function bodies, in macro invocations or generated by macros are not listed.
/// An `impl` is named by its self type as Thrust's selection names it: the last segment of a
/// path type, or `{impl}` for a type that is not a path (a reference, a tuple), a primitive or
/// a type parameter of the impl. A type alias is named by itself, where Thrust names the type
/// it stands for.
export function functionsIn(text: string): FnItem[] {
  return new Scanner(tokenize(text)).run();
}

/// The path of `fn` for `THRUST_VERIFY_ONLY`, in the module `modulePath` of the crate.
export function selectionPath(modulePath: string[], fn: FnItem): string {
  return [...modulePath, ...fn.path].join("::");
}

/// The module path of `file` in the crate whose root file is `root`: none for the root itself,
/// `a::b` for `a/b.rs` or `a/b/mod.rs` next to it; undefined for a file outside its directory.
/// `#[path]` attributes are not read.
export function modulePathOf(file: string, root: string): string[] | undefined {
  if (path.resolve(file) === path.resolve(root)) {
    return [];
  }
  const relative = path.relative(path.dirname(root), file);
  if (relative.startsWith("..") || path.isAbsolute(relative) || !relative.endsWith(".rs")) {
    return undefined;
  }
  const segments = relative.slice(0, -".rs".length).split(path.sep);
  if (segments[segments.length - 1] === "mod") {
    segments.pop();
  }
  return segments;
}

const IDENT_START = /[\p{XID_Start}_]/u;
const IDENT_CONTINUE = /[\p{XID_Continue}]/u;
const JOINED = ["::", "->", "=>"];

function tokenize(text: string): Token[] {
  const tokens: Token[] = [];
  const chars = Array.from(text);
  let i = 0;
  let line = 1;
  const advance = (count: number) => {
    for (let k = 0; k < count && i < chars.length; k++, i++) {
      if (chars[i] === "\n") {
        line++;
      }
    }
  };
  const at = (k: number) => chars[i + k] ?? "";
  while (i < chars.length) {
    const c = at(0);
    const start = line;
    if (/\s/u.test(c)) {
      advance(1);
    } else if (c === "/" && at(1) === "/") {
      while (i < chars.length && at(0) !== "\n") advance(1);
    } else if (c === "/" && at(1) === "*") {
      advance(blockCommentLength(chars, i));
    } else if (rawStringPrefix(chars, i) !== undefined) {
      advance(rawStringLength(chars, i));
      tokens.push({ text: "\"\"", kind: "literal", line: start });
    } else if (c === "\"" || ((c === "b" || c === "c") && at(1) === "\"")) {
      advance(quotedLength(chars, c === "\"" ? i : i + 1, "\"") + (c === "\"" ? 0 : 1));
      tokens.push({ text: "\"\"", kind: "literal", line: start });
    } else if (c === "'" || (c === "b" && at(1) === "'")) {
      const offset = c === "'" ? 0 : 1;
      const quote = i + offset;
      if (chars[quote + 1] === "\\" || chars[quote + 2] === "'") {
        advance(quotedLength(chars, quote, "'") + offset);
        tokens.push({ text: "''", kind: "literal", line: start });
      } else {
        advance(1 + offset);
        let name = "'";
        while (i < chars.length && IDENT_CONTINUE.test(at(0))) {
          name += at(0);
          advance(1);
        }
        tokens.push({ text: name, kind: "lifetime", line: start });
      }
    } else if (c === "r" && at(1) === "#" && IDENT_START.test(at(2))) {
      advance(2);
      tokens.push({ text: identAt(), kind: "ident", line: start });
    } else if (IDENT_START.test(c)) {
      tokens.push({ text: identAt(), kind: "ident", line: start });
    } else if (/[0-9]/.test(c)) {
      while (i < chars.length && /[0-9A-Za-z_]/.test(at(0))) advance(1);
      tokens.push({ text: "0", kind: "literal", line: start });
    } else {
      const joined = JOINED.find((j) => c + at(1) === j);
      advance(joined ? 2 : 1);
      tokens.push({ text: joined ?? c, kind: "punct", line: start });
    }
  }
  return tokens;

  function identAt(): string {
    let name = "";
    while (i < chars.length && IDENT_CONTINUE.test(at(0))) {
      name += at(0);
      advance(1);
    }
    return name;
  }
}

/// The length of the (nested) block comment at `start`.
function blockCommentLength(chars: string[], start: number): number {
  let depth = 0;
  let i = start;
  while (i < chars.length) {
    if (chars[i] === "/" && chars[i + 1] === "*") {
      depth++;
      i += 2;
    } else if (chars[i] === "*" && chars[i + 1] === "/") {
      depth--;
      i += 2;
      if (depth === 0) {
        break;
      }
    } else {
      i++;
    }
  }
  return i - start;
}

/// The length of the literal opened by `quote` at `start`, escapes skipped.
function quotedLength(chars: string[], start: number, quote: string): number {
  let i = start + 1;
  while (i < chars.length && chars[i] !== quote) {
    i += chars[i] === "\\" ? 2 : 1;
  }
  return i + 1 - start;
}

/// The number of `#` of a raw string starting at `start` (`r"`, `r#"`, `br"`, `cr#"`), if one does.
function rawStringPrefix(chars: string[], start: number): number | undefined {
  let i = start;
  if ((chars[i] === "b" || chars[i] === "c") && chars[i + 1] === "r") {
    i++;
  }
  if (chars[i] !== "r") {
    return undefined;
  }
  i++;
  let hashes = 0;
  while (chars[i] === "#") {
    hashes++;
    i++;
  }
  return chars[i] === "\"" ? hashes : undefined;
}

function rawStringLength(chars: string[], start: number): number {
  const hashes = rawStringPrefix(chars, start) ?? 0;
  const close = "\"" + "#".repeat(hashes);
  let i = chars.indexOf("\"", start) + 1;
  while (i < chars.length && chars.slice(i, i + close.length).join("") !== close) {
    i++;
  }
  return Math.min(i + close.length, chars.length) - start;
}

type FrameKind = "container" | "fn" | "other";

interface Frame {
  kind: FrameKind;
  /// The path segments a function inside this frame is under.
  path: string[];
  /// Whether the frame is compiled only for tests (`#[cfg(test)]`, `#[test]`), which
  /// `cargo check` leaves out, so its functions get no lens.
  testOnly: boolean;
  /// For a function's frame, what it was opened for.
  fn?: FnItem;
}

const QUALIFIERS = new Set(["default", "const", "async", "unsafe", "safe", "extern"]);
const PRIMITIVES = new Set([
  "bool", "char", "str", "i8", "i16", "i32", "i64", "i128", "isize",
  "u8", "u16", "u32", "u64", "u128", "usize", "f16", "f32", "f64", "f128",
]);

/// The keywords a type that is not a path starts with.
const NOT_PATHS = new Set(["dyn", "impl", "fn", "unsafe", "extern"]);

class Scanner {
  private readonly frames: Frame[] = [{ kind: "container", path: [], testOnly: false }];
  private readonly found: FnItem[] = [];
  /// The tokens of the item being read in a container, attributes left out, and the line it
  /// starts at, its first attribute's.
  private header: Token[] = [];
  private headerLine: number | undefined;
  /// The item's attributes, each its tokens joined (`cfg(test)`).
  private attributes: string[] = [];
  /// The depth of parentheses and brackets in the header, where `;`, `{` and `}` belong to it
  /// (`fn f(a: [u8; 4])`, `-> [u8; { N }]`).
  private nesting = 0;
  private i = 0;

  constructor(private readonly tokens: Token[]) {}

  run(): FnItem[] {
    while (this.i < this.tokens.length) {
      this.step();
    }
    return this.found;
  }

  private top(): Frame {
    return this.frames[this.frames.length - 1];
  }

  private step(): void {
    const token = this.tokens[this.i];
    if (this.top().kind !== "container") {
      this.inBody(token);
      return;
    }
    if (token.text === "#" && this.isAttribute()) {
      this.headerLine ??= token.line;
      this.attributes.push(this.skipAttribute());
      return;
    }
    this.i++;
    if (this.nesting > 0 || "([".includes(token.text)) {
      this.nesting += "([{".includes(token.text) ? 1 : ")]}".includes(token.text) ? -1 : 0;
      this.header.push(token);
    } else if (token.text === "{") {
      this.open();
    } else if (token.text === "}") {
      this.close(token);
    } else if (token.text === ";") {
      this.reset();
    } else {
      this.headerLine ??= token.line;
      this.header.push(token);
    }
  }

  /// Inside a function's body or another block: only the braces count.
  private inBody(token: Token): void {
    this.i++;
    if (token.text === "{") {
      this.frames.push({ kind: "other", path: this.top().path, testOnly: this.top().testOnly });
    } else if (token.text === "}") {
      this.close(token);
    }
  }

  private isAttribute(): boolean {
    const next = this.tokens[this.i + 1]?.text;
    return next === "[" || (next === "!" && this.tokens[this.i + 2]?.text === "[");
  }

  /// Skips the attribute at the cursor; its tokens inside the brackets, joined.
  private skipAttribute(): string {
    while (this.tokens[this.i].text !== "[") {
      this.i++;
    }
    const start = this.i + 1;
    let depth = 0;
    for (; this.i < this.tokens.length; this.i++) {
      const text = this.tokens[this.i].text;
      depth += "([{".includes(text) ? 1 : ")]}".includes(text) ? -1 : 0;
      if (depth === 0) {
        this.i++;
        break;
      }
    }
    return this.tokens.slice(start, this.i - 1).map((t) => t.text).join("");
  }

  private reset(): void {
    this.header = [];
    this.headerLine = undefined;
    this.attributes = [];
    this.nesting = 0;
  }

  /// A `{` in a container opens the item its header says.
  private open(): void {
    const parent = this.top();
    const words = withoutVisibility(this.header);
    const fnName = functionName(words);
    const testOnly = parent.testOnly || this.attributes.some(isTestAttribute);
    const container = (name: string): Frame => ({ kind: "container", path: [...parent.path, name], testOnly });
    if (fnName !== undefined) {
      const fn: FnItem = { name: fnName, path: [...parent.path, fnName], line: this.headerLine ?? 1, endLine: 0 };
      this.frames.push({ kind: "fn", path: fn.path, fn, testOnly });
    } else if (words[0]?.text === "mod" && words[1]?.kind === "ident") {
      this.frames.push(container(words[1].text));
    } else if (words[0]?.text === "trait" || (words[0]?.text === "unsafe" && words[1]?.text === "trait")) {
      const name = words.find((w, k) => k > 0 && w.kind === "ident" && w.text !== "trait");
      this.frames.push(container(name?.text ?? "_"));
    } else if (isImplHeader(words)) {
      this.frames.push(container(implSelfName(words)));
    } else {
      this.frames.push({ kind: "other", path: parent.path, testOnly });
    }
    this.reset();
  }

  private close(token: Token): void {
    const frame = this.frames.length > 1 ? this.frames.pop() : undefined;
    if (frame?.fn && !frame.testOnly) {
      frame.fn.endLine = token.line;
      this.found.push(frame.fn);
    }
    if (this.top().kind === "container") {
      this.reset();
    }
  }
}

/// Whether an attribute makes its item compiled for tests only: `cfg(test)`, or a test
/// function's (`test`, `tokio::test`).
function isTestAttribute(attribute: string): boolean {
  return attribute === "cfg(test)" || /^(\w+::)*test$/.test(attribute);
}

/// The header without a leading `pub`, `pub(crate)` or `pub(in path)`.
function withoutVisibility(header: Token[]): Token[] {
  if (header[0]?.text !== "pub") {
    return header;
  }
  if (header[1]?.text !== "(") {
    return header.slice(1);
  }
  const close = header.findIndex((t) => t.text === ")");
  return close < 0 ? header.slice(1) : header.slice(close + 1);
}

/// The name of the function the header declares: `fn name` after qualifiers (`const`, `async`,
/// `unsafe`, `extern "C"`).
function functionName(words: Token[]): string | undefined {
  let k = 0;
  while (k < words.length && (QUALIFIERS.has(words[k].text) || (words[k].kind === "literal" && words[k - 1]?.text === "extern"))) {
    k++;
  }
  return words[k]?.text === "fn" && words[k + 1]?.kind === "ident" ? words[k + 1].text : undefined;
}

/// Whether the header is `[unsafe] impl ...`.
function isImplHeader(words: Token[]): boolean {
  return words[0]?.text === "impl" || (words[0]?.text === "unsafe" && words[1]?.text === "impl");
}

/// The name of an impl's self type, as Thrust's selection names the impl.
function implSelfName(words: Token[]): string {
  let k = words.findIndex((w) => w.text === "impl") + 1;
  const params = new Set<string>();
  if (words[k]?.text === "<") {
    k = genericParams(words, k, params);
  }
  const end = words.findIndex((w, j) => j >= k && w.text === "where");
  const type = words.slice(k, end < 0 ? words.length : end);
  const forAt = topLevelIndex(type, "for");
  const selfType = forAt < 0 ? type : type.slice(forAt + 1);
  return pathTypeName(withoutParens(selfType), params) ?? "{impl}";
}

/// Reads the generic parameters `<...>` at `k` into `params`: the first identifier of each, after
/// `const`. Returns the index after them.
function genericParams(words: Token[], k: number, params: Set<string>): number {
  let depth = 0;
  let expectName = false;
  for (; k < words.length; k++) {
    const word = words[k];
    if (word.text === "<" || word.text === ">") {
      depth += word.text === "<" ? 1 : -1;
      if (depth === 0) {
        return k + 1;
      }
      expectName = word.text === "<" && depth === 1;
    } else if (depth === 1 && word.text === ",") {
      expectName = true;
    } else if (expectName && word.text !== "const") {
      if (word.kind === "ident") {
        params.add(word.text);
      }
      expectName = false;
    }
  }
  return k;
}

/// A parenthesized type without its parentheses (`(Foo)` is `Foo`); a tuple is left as it is.
function withoutParens(type: Token[]): Token[] {
  if (type[0]?.text !== "(" || type[type.length - 1]?.text !== ")") {
    return type;
  }
  const inner = type.slice(1, -1);
  return closingBefore(inner) || topLevelIndex(inner, ",") >= 0 ? type : withoutParens(inner);
}

/// Whether the tokens close more than they open somewhere: `(A) -> (B)` read without its outer
/// parentheses.
function closingBefore(tokens: Token[]): boolean {
  let depth = 0;
  for (const token of tokens) {
    depth += "(<[".includes(token.text) ? 1 : ")>]".includes(token.text) ? -1 : 0;
    if (depth < 0) {
      return true;
    }
  }
  return false;
}

function topLevelIndex(tokens: Token[], text: string): number {
  let depth = 0;
  for (let k = 0; k < tokens.length; k++) {
    const t = tokens[k].text;
    depth += t === "<" || t === "(" || t === "[" ? 1 : t === ">" || t === ")" || t === "]" ? -1 : 0;
    if (depth === 0 && t === text) {
      return k;
    }
  }
  return -1;
}

/// The last segment of a path type (`a::B<T>` is `B`), unless it is a primitive or one of the
/// impl's parameters; undefined for a type that is not a path.
function pathTypeName(type: Token[], params: Set<string>): string | undefined {
  if (NOT_PATHS.has(type[0]?.text ?? "")) {
    return undefined;
  }
  let last: string | undefined;
  for (const token of type) {
    if (token.text === "<") {
      break;
    }
    if (token.kind === "ident") {
      last = token.text;
    } else if (token.text !== "::") {
      return undefined;
    }
  }
  if (last === undefined || PRIMITIVES.has(last) || params.has(last)) {
    return undefined;
  }
  return last;
}
